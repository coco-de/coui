/// Position enum for tooltip placement relative to its target.
library;

/// The position where a tooltip is displayed relative to its target.
enum CoreTooltipPosition {
  /// Tooltip appears above the target.
  top,

  /// Tooltip appears below the target.
  bottom,

  /// Tooltip appears to the left of the target.
  left,

  /// Tooltip appears to the right of the target.
  right,
}
