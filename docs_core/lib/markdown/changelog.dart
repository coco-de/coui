/// Pure parsing for `release-please`-generated `CHANGELOG.md` files.
///
/// Kept free of `dart:io` so it is unit-testable with plain strings — the
/// file read itself lives in `changelog_preview_component.dart`, which is
/// the only place that needs a working directory assumption.
library;

/// One release entry: a version, its release date, and its changelog
/// sections (Korean section titles from `release-please-config.json`'s
/// `changelog-sections`, e.g. `기능` / `버그 수정` / `리팩터링`).
class ChangelogEntry {
  const ChangelogEntry({
    required this.version,
    required this.date,
    required this.sections,
  });

  /// e.g. `0.128.1`. Markdown link syntax (`[0.128.1](url)`) is already
  /// stripped.
  final String version;

  /// e.g. `2026-07-25` (ISO date as written in the changelog).
  final String date;

  /// Section title → bullet lines (markdown link/commit-hash noise is not
  /// stripped here — that is a rendering concern, not a parsing concern).
  final Map<String, List<String>> sections;
}

/// Matches both the current `release-please` header
/// (`## [0.128.1](https://…) (2026-07-25)`) and the legacy plain header
/// still present at the bottom of older changelogs (`## 0.127.15
/// (2026-06-16)`) — the root `CHANGELOG.md` was generated by an earlier
/// tool config and never fully migrated, so both forms exist in the wild.
final _headerPattern = RegExp(
  r'^## (?:\[(?<linked>[^\]]+)\]\([^)]*\)|(?<bare>\S+))\s*\((?<date>\d{4}-\d{2}-\d{2})\)\s*$',
);

final _sectionPattern = RegExp(r'^### (.+)$');

/// A top-level bullet — `* ` (release-please) or `- ` (legacy generator).
/// Deliberately does not match indented sub-bullets, which are rare in
/// this changelog style and would otherwise attach to the wrong entry.
final _bulletPattern = RegExp(r'^[*-] (.+)$');

/// Parses the first [limit] release entries from a `CHANGELOG.md` source
/// string, in file order (newest first — `release-please` always prepends).
///
/// Unknown/malformed lines between a section heading and its bullets (blank
/// lines, `release-please`'s empty line after the version header) are
/// ignored rather than rejected — the goal is a best-effort preview, not a
/// strict validator. A file with zero parseable entries returns `[]`
/// rather than throwing, so a preview embed degrades to "no entries" over
/// churning during the doc build.
List<ChangelogEntry> parseChangelogEntries(String source, {int limit = 5}) {
  if (limit <= 0) return const [];

  final entries = <ChangelogEntry>[];
  String? version;
  String? date;
  Map<String, List<String>> sections = {};
  String? currentSection;

  void flush() {
    final v = version;
    final d = date;
    if (v != null && d != null) {
      entries.add(ChangelogEntry(version: v, date: d, sections: sections));
    }
  }

  for (final line in source.split('\n')) {
    final header = _headerPattern.firstMatch(line);
    if (header != null) {
      flush();
      if (entries.length >= limit) return entries;
      version = header.namedGroup('linked') ?? header.namedGroup('bare');
      date = header.namedGroup('date');
      sections = {};
      currentSection = null;
      continue;
    }
    if (version == null) continue; // Skip preamble before the first header.

    final section = _sectionPattern.firstMatch(line);
    if (section != null) {
      currentSection = section.group(1)!.trim();
      sections.putIfAbsent(currentSection, () => []);
      continue;
    }

    final bullet = _bulletPattern.firstMatch(line);
    if (bullet != null && currentSection != null) {
      sections[currentSection]!.add(bullet.group(1)!.trim());
    }
  }
  flush();

  return entries.length > limit ? entries.sublist(0, limit) : entries;
}

/// Strips markdown link syntax (`[text](url)`) down to `text`, and the
/// trailing commit-hash/issue-link noise `release-please` appends to every
/// bullet (`([#123](url)) ([abcdef0](url))`) — kept so a plain-text
/// preview stays readable without a full markdown-to-HTML pass.
String stripChangelogNoise(String text) {
  return text
      .replaceAllMapped(RegExp(r'\[([^\]]*)\]\([^)]*\)'), (m) => m.group(1) ?? '')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
}

/// What a piece of a changelog bullet is.
enum ChangelogSpanKind {
  /// Plain text.
  text,

  /// `**bold**` — `release-please` writes the commit scope this way
  /// (`**button:**`).
  strong,

  /// `` `code` `` — an identifier in the commit subject.
  code,
}

/// One piece of a changelog bullet.
typedef ChangelogSpan = ({ChangelogSpanKind kind, String text});

/// Splits a bullet into the pieces a renderer draws.
///
/// Links collapse to their text first ([stripChangelogNoise]), then
/// `**bold**` and `` `code` `` become their own spans. Both documentation
/// surfaces — the site's timeline and the native app's list — draw a
/// bullet from these spans, so the markers never reach the reader as
/// literal asterisks and backticks, and the two surfaces cannot disagree
/// on what is bold. A marker without its closing pair stays as text.
List<ChangelogSpan> changelogBulletSpans(String bullet) {
  final text = stripChangelogNoise(bullet);
  final spans = <ChangelogSpan>[];
  var cursor = 0;
  for (final match in RegExp(r'\*\*([^*]+)\*\*|`([^`]+)`').allMatches(text)) {
    if (match.start > cursor) {
      spans.add((kind: ChangelogSpanKind.text, text: text.substring(cursor, match.start)));
    }
    final strong = match.group(1);
    spans.add(
      strong == null
          ? (kind: ChangelogSpanKind.code, text: match.group(2)!)
          : (kind: ChangelogSpanKind.strong, text: strong),
    );
    cursor = match.end;
  }
  if (cursor < text.length) spans.add((kind: ChangelogSpanKind.text, text: text.substring(cursor)));
  return spans;
}

/// How many entries `<ChangelogPreview>` shows when `count` is absent or not
/// a number.
const kChangelogPreviewDefaultCount = 5;

/// The packages `<ReleaseTimeline />` reads, in the order a release lists
/// them.
///
/// One list for both documentation surfaces — the site's timeline and the
/// native app's list — so a package added to the timeline cannot appear on
/// one surface only.
const kReleaseTimelinePackages = ['coui_flutter', 'coui_web', 'coui_core'];

/// How many releases of each package `<ReleaseTimeline />` reads.
const kReleaseTimelinePerPackage = 8;

/// How many releases the timeline shows before folding the rest away.
const kReleaseTimelineVisible = 3;

/// What a `<ChangelogPreview>` tag shows — release entries, or a one-line
/// notice when there are none to show.
///
/// Both documentation surfaces (the Jaspr site and the native app) render
/// this value. Only *reading* the changelog differs between them (a file on
/// disk vs a bundled asset); which entries appear, in which order, and how a
/// failure reads is decided here — two surfaces reading one CHANGELOG
/// differently is a difference nobody looks at.
sealed class ChangelogPreviewView {
  const ChangelogPreviewView();
}

/// The newest entries, newest first.
final class ChangelogPreviewEntries extends ChangelogPreviewView {
  const ChangelogPreviewEntries(this.entries);

  final List<ChangelogEntry> entries;
}

/// Why nothing can be shown — rendered in place of the entries, so a renamed
/// package degrades the page instead of breaking it.
final class ChangelogPreviewNotice extends ChangelogPreviewView {
  const ChangelogPreviewNotice(this.message);

  final String message;
}

/// The `package` attribute, or `null` when it is missing or empty.
String? changelogPreviewPackage(Map<String, String> attributes) {
  final package = attributes['package'];
  return package == null || package.isEmpty ? null : package;
}

/// Shown when the tag has no `package` attribute.
const kChangelogPreviewMissingPackageNotice = ChangelogPreviewNotice(
  '<ChangelogPreview> is missing a required `package` attribute.',
);

/// Shown when the package has no CHANGELOG to read.
ChangelogPreviewNotice changelogPreviewMissingNotice(String package) =>
    ChangelogPreviewNotice('$package has no CHANGELOG.md yet.');

/// Shown when the CHANGELOG exists but could not be read.
ChangelogPreviewNotice changelogPreviewUnreadableNotice(String package, Object error) =>
    ChangelogPreviewNotice('Could not read $package/CHANGELOG.md ($error).');

/// Decides what `<ChangelogPreview>` shows once the CHANGELOG source is in
/// hand. `count` limits the entries (default [kChangelogPreviewDefaultCount]).
ChangelogPreviewView changelogPreviewView({
  required String package,
  required Map<String, String> attributes,
  required String changelogSource,
}) {
  final count = int.tryParse(attributes['count'] ?? '') ?? kChangelogPreviewDefaultCount;
  final entries = parseChangelogEntries(changelogSource, limit: count);
  if (entries.isEmpty) {
    return ChangelogPreviewNotice('$package/CHANGELOG.md has no parseable release entries yet.');
  }
  return ChangelogPreviewEntries(entries);
}
