/// 컴포넌트 페이지 레지스트리 생성기.
///
/// 컴포넌트 페이지(v2 템플릿)의 플레이그라운드 · 크기 표 · 미리보기는
/// 컴포넌트마다 `lib/pages/<dir>/` 의 세 파일에 산다:
///
/// - `<dir>_page.dart` — 순수 Dart. `slug` · `playground` · `sizeSpec`.
/// - `<dir>_web.dart` — Jaspr. `propPreview` · `demos`.
/// - `<dir>_flutter.dart` — Flutter. `propPreview` · `demos`.
///
/// 이 도구가 폴더를 찾아 세 레지스트리(`page_registry*.g.dart`)를 쓴다.
/// 레지스트리를 손으로 적지 않는 이유는 여러 사람이 동시에 페이지를 더할 때다
/// — 한 파일의 맵에 줄을 더하면 서로 충돌하고, 폴더는 충돌하지 않는다.
/// 충돌이 나면 이 도구를 다시 돌리면 된다.
///
/// ```sh
/// dart run tool/gen_page_registry.dart          # 쓴다
/// dart run tool/gen_page_registry.dart --check  # 낡았으면 실패
/// ```
library;

import 'dart:io';

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final outputs = renderPageRegistry(Directory('lib/pages'));
  var stale = false;
  for (final MapEntry(key: path, value: content) in outputs.entries) {
    final file = File(path);
    final current = file.existsSync() ? file.readAsStringSync() : null;
    if (current == content) continue;
    if (check) {
      stderr.writeln('낡음: $path — dart run tool/gen_page_registry.dart 로 다시 쓰세요.');
      stale = true;
    } else {
      file.writeAsStringSync(content);
      stdout.writeln('씀: $path');
    }
  }
  if (stale) exitCode = 1;
}

/// 페이지 폴더 하나.
class PageFolder {
  const PageFolder({required this.dir, required this.slug});

  /// 폴더 이름 — 파일 이름의 앞부분이자 import 접두어.
  final String dir;

  /// 문서 슬러그.
  final String slug;
}

/// [root] 아래의 페이지 폴더 — 폴더 이름 순.
List<PageFolder> findPageFolders(Directory root) {
  final folders = <PageFolder>[];
  final dirs = root.listSync().whereType<Directory>().toList()..sort((a, b) => a.path.compareTo(b.path));
  for (final dir in dirs) {
    final name = dir.uri.pathSegments.lastWhere((s) => s.isNotEmpty);
    final page = File('${dir.path}/${name}_page.dart');
    if (!page.existsSync()) continue;
    for (final platform in const ['web', 'flutter']) {
      if (!File('${dir.path}/${name}_$platform.dart').existsSync()) {
        throw StateError('${dir.path}: ${name}_$platform.dart 가 없습니다.');
      }
    }
    final slug = RegExp(r"^const String slug = '([a-z0-9-]+)';", multiLine: true).firstMatch(page.readAsStringSync());
    if (slug == null) throw StateError("${page.path}: `const String slug = '...';` 가 없습니다.");
    folders.add(PageFolder(dir: name, slug: slug.group(1)!));
  }
  return folders;
}

/// 경로 → 내용.
Map<String, String> renderPageRegistry(Directory root) {
  final folders = findPageFolders(root);
  const header =
      '// GENERATED by tool/gen_page_registry.dart — 손으로 고치지 마세요.\n'
      '// 페이지는 lib/pages/<dir>/ 에 더하고 도구를 다시 돌립니다.\n'
      '// ignore_for_file: directives_ordering\n\n';
  String imports(String suffix) => [
    for (final f in folders) "import '${f.dir}/${f.dir}_$suffix.dart' as ${f.dir};",
  ].join('\n');

  final shared = StringBuffer(header)
    ..writeln("import '../shared/playground_spec.dart';")
    ..writeln("import '../shared/size_spec.dart';")
    ..writeln(imports('page'))
    ..writeln()
    ..writeln('/// 문서 슬러그 → 플레이그라운드.')
    ..writeln('final Map<String, DocsPlaygroundSpec> kDocsPlaygrounds = {');
  for (final f in folders) {
    shared.writeln('  if (${f.dir}.playground case final spec?) ${f.dir}.slug: spec,');
  }
  shared
    ..writeln('};')
    ..writeln()
    ..writeln('/// 문서 슬러그 → 크기 표.')
    ..writeln('final Map<String, DocsSizeSpec Function()> kDocsSizeSpecs = {');
  for (final f in folders) {
    shared.writeln('  if (${f.dir}.sizeSpec case final spec?) ${f.dir}.slug: spec,');
  }
  shared.writeln('};');

  String platform(String suffix, String builderType, String sceneType, String prefix, String typesImport) {
    final package = suffix == 'web' ? 'coui_web/coui_web.dart' : 'coui_flutter/coui_flutter.dart';
    final out = StringBuffer(header)
      ..writeln("import 'package:$package' show $sceneType;")
      ..writeln()
      ..writeln("import '$typesImport';")
      ..writeln(imports(suffix))
      ..writeln()
      ..writeln('/// 문서 슬러그 → 속성 빌더.')
      ..writeln('final Map<String, $builderType> k${prefix}PropPreviews = {');
    for (final f in folders) {
      out.writeln("  if (${f.dir}.propPreview case final builder?) '${f.slug}': builder,");
    }
    out
      ..writeln('};')
      ..writeln()
      ..writeln('/// 장면 이름 → 장면.')
      ..writeln('final Map<String, $sceneType Function()> k${prefix}DocDemos = {');
    for (final f in folders) {
      out.writeln('  ...${f.dir}.demos,');
    }
    out.writeln('};');
    return out.toString();
  }

  return {
    '${root.path}/page_registry.g.dart': shared.toString(),
    '${root.path}/page_registry_web.g.dart': platform(
      'web',
      'WebPropPreviewBuilder',
      'Component',
      'Web',
      '../previews/props/web_prop_previews.dart',
    ),
    '${root.path}/page_registry_flutter.g.dart': platform(
      'flutter',
      'FlutterPropPreviewBuilder',
      'Widget',
      'Flutter',
      '../previews/props/flutter_prop_previews.dart',
    ),
  };
}
