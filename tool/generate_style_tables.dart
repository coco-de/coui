#!/usr/bin/env dart

// This is a CLI script — its whole job is printing progress/results, so a
// logging framework would add ceremony without a reader that benefits.
// ignore_for_file: avoid_print

/// Generates the "`CoreXxxStyle` 필드" and per-axis ("변형별" / "색별" /
/// "톤별") 기본값 markdown tables for a component doc straight from its
/// `CoreXxxStyle` source
/// (`packages/coui_core/lib/src/component/contracts/{slug}/{slug}_style.dart`).
///
/// Why a generator instead of hand-written tables:
/// `CoreXxxStyle.defaultsByVariant` already holds the field × variant ×
/// token relationship as code. A second, hand-maintained copy of the same
/// relationship in markdown is a second place to forget to update — the
/// same divergence risk this docs-automation work closes for CHANGELOG
/// links and version strings, applied here to Style field tables.
///
/// The parser is intentionally regex/bracket-depth based (no `analyzer`
/// dependency), matching `docs_core/test/registry/docs_api_sync_test.dart`'s
/// existing approach to reading contract source — the point is not a
/// general Dart parser, it is a reader for the narrow, consistently
/// formatted shape `core/style-contract.md` requires every `CoreXxxStyle`
/// to have (nullable instance fields + `static const default*` +
/// `static const defaultsByVariant` of `CoreXxxVariantStyle` literals, and
/// optionally a `defaultsByTone` of `CoreXxxToneStyle` literals). A
/// file whose shape this cannot read is skipped, not guessed at — see
/// `main()`'s `--check` coverage report.
///
/// Usage:
///   dart run tool/generate_style_tables.dart --write card button badge
///   dart run tool/generate_style_tables.dart --write        # every slug
///   dart run tool/generate_style_tables.dart --check         # CI gate
library;

import 'dart:io';

// ── Markers ──────────────────────────────────────────────────────────────

/// Wraps the generated block in the target `.md` file. Present already →
/// regenerate in place. Absent → this tool never inserts them on its own
/// (see `main()`); a doc opts in by adding this pair once, by hand or via
/// `_templates/component.md`.
///
/// No literal `--` may appear inside an HTML comment body — the WHATWG
/// tokenizer rejects it ("unexpected-char-in-comment") and `jaspr build`'s
/// markdown pipeline throws a 500 building the page. An earlier version of
/// this marker read `` `dart run tool/generate_style_tables.dart --write` ``
/// inline, which broke every doc it had been inserted into; `--write` is
/// now spelled `write mode` instead. Guarded by a test asserting neither
/// marker contains `--` outside its own `<!--`/`-->` delimiters.
const kStyleTableBeginMarker =
    '<!-- STYLE_TABLE:BEGIN — auto-generated by `dart run '
    'tool/generate_style_tables.dart` (write mode). Do not hand-edit '
    'between these markers; edit the CoreXxxStyle source and regenerate. -->';
const kStyleTableEndMarker = '<!-- STYLE_TABLE:END -->';

// ── Data model ───────────────────────────────────────────────────────────

class StyleField {
  const StyleField({
    required this.name,
    required this.type,
    this.description,
    this.deprecation,
  });
  final String name;
  final String type;

  /// The field's doc comment, sanitized — never the annotation text.
  final String? description;

  /// The field's `@Deprecated(...)` message, its adjacent string literals
  /// joined. `''` for a bare `@deprecated` (or an empty message); `null`
  /// when the field is not deprecated.
  ///
  /// Kept apart from [description] because the two answer different
  /// questions — the doc comment says what the field *is*, the annotation
  /// says whether to use it. [describeField] composes them for the table.
  final String? deprecation;
}

class ParsedStyleFile {
  const ParsedStyleFile({
    required this.className,
    required this.fields,
    this.variantEnumType,
    this.variantStyleClassName,
    this.variantDefaults = const [],
    this.axisLabel = '변형별',
    this.toneStyleClassName,
    this.toneDefaults = const [],
  });

  final String className;
  final List<StyleField> fields;

  /// Non-null only when the file has a `defaultsByVariant` map.
  final String? variantEnumType;
  final String? variantStyleClassName;

  /// Variant short name (e.g. `outlined`) → field name → formatted value,
  /// in source order.
  final List<MapEntry<String, Map<String, String>>> variantDefaults;

  /// What the per-entry table calls its axis in the heading — `변형별` for
  /// a `defaultsByVariant` map, `색별` for a `defaultsByColor` map (a
  /// component whose `variant` names something else, so its colour table
  /// is keyed by the colour enum).
  final String axisLabel;

  /// Non-null only when the file has a `defaultsByTone` map whose rows are
  /// a row class of their own (`CoreXxxToneStyle`) — see [parseStyleFile].
  final String? toneStyleClassName;

  /// Tone short name (e.g. `success`) → field name → formatted value, in
  /// source order. Rendered as a second per-axis table next to
  /// [variantDefaults], because a component can key its colours by tone
  /// and still have a variant axis that means something else (strength).
  final List<MapEntry<String, Map<String, String>>> toneDefaults;
}

// ── Bracket-depth helpers (shared shape with docs_api_sync_test.dart) ────

/// Strips `///` and `//` comments — used only for the structural pass
/// (finding class/map bodies, splitting call arguments). Doc-comment text
/// itself is read from the *original* source in a separate pass, since
/// stripping happens before we would otherwise capture it.
String _stripComments(String source) {
  return source
      .replaceAll(RegExp(r'^\s*///.*$', multiLine: true), '')
      .replaceAll(RegExp('//.*'), '');
}

/// Finds the `{...}` body of `class $name` (or `Map<...> $name =`) starting
/// at the first `{` after the declaration, and returns the body text
/// (excluding the outer braces) plus the offset just past the closing `}`.
/// Returns `null` if `name` is not declared or the braces are unbalanced.
({String body, int end})? _bracedBodyAfter(
  String source,
  Pattern declarationStart,
) {
  final startSearch = source.indexOf(declarationStart);
  if (startSearch < 0) return null;
  final open = source.indexOf('{', startSearch);
  if (open < 0) return null;

  var depth = 0;
  for (var i = open; i < source.length; i++) {
    final char = source[i];
    if (char == '{') depth++;
    if (char == '}') {
      depth--;
      if (depth == 0) {
        return (body: source.substring(open + 1, i), end: i + 1);
      }
    }
  }
  return null; // Unbalanced — treat as unparseable.
}

/// Splits `text` on top-level commas (depth 0 for `(<[{`), same rule
/// `docs_api_sync_test.dart`'s `ctorParams` uses for constructor args.
List<String> _splitTopLevel(String text) {
  final parts = <String>[];
  var depth = 0;
  final chunk = StringBuffer();
  for (final char in text.split('')) {
    if ('(<[{'.contains(char)) depth++;
    if (')>]}'.contains(char)) depth--;
    if (char == ',' && depth == 0) {
      parts.add(chunk.toString());
      chunk.clear();
    } else {
      chunk.write(char);
    }
  }
  final last = chunk.toString().trim();
  if (last.isNotEmpty) parts.add(last);
  return parts.map((p) => p.trim()).where((p) => p.isNotEmpty).toList();
}

// ── Field parsing (doc comments come from the original, un-stripped source) ──

List<StyleField> _parseFields(String classBodyOriginal) {
  final fields = <StyleField>[];
  final docBuffer = <String>[];
  // A field has no initializer. `[^=]` keeps a local in a method body
  // (`final a = gradient;` inside `operator ==`) from reading as a field
  // named after its initializer.
  final fieldLine = RegExp(r'^(?!\s*static)\s*final\s+([^=]+?)\s+(\w+);\s*$');
  // `dart format`'s canonical order is doc comment, then annotation
  // (`@Deprecated(...)`), then the field itself. The annotation must not
  // reset `docBuffer` the way an unrelated line would, and its *content*
  // must reach the table: a generated table is trusted to match its source,
  // so one that drops `@Deprecated` tells the reader the field is alive.
  //
  // Text of an annotation whose argument list spans several lines, while
  // it is still open.
  final openAnnotation = StringBuffer();
  // Set by `@Deprecated(...)` / `@deprecated`, taken by the next field, and
  // dropped by any unrelated declaration in between — a deprecated
  // `static const default*`, a constructor parameter, a getter — so it can
  // never land on the wrong field.
  String? pendingDeprecation;
  // Set by the first blank `///` line after some text. Only the summary
  // paragraph — the part of a field's doc comment written for the people
  // who use the kit — reaches the table; the paragraphs after it are notes
  // for the people who change the field, and stay in the source.
  var summaryEnded = false;

  void noteAnnotation(String annotation) {
    final name = RegExp(r'^@([\w.]+)').firstMatch(annotation)?.group(1);
    if (name == 'Deprecated' || name == 'deprecated') {
      pendingDeprecation = _stringLiteralText(annotation);
    }
  }

  for (final rawLine in classBodyOriginal.split('\n')) {
    var rest = rawLine.trim();

    if (openAnnotation.isNotEmpty) {
      openAnnotation
        ..write('\n')
        ..write(rest);
      final text = openAnnotation.toString();
      final end = _annotationEndOffset(text);
      if (end == null) continue;
      openAnnotation.clear();
      noteAnnotation(text.substring(0, end));
      rest = text.substring(end).trim();
    }

    if (rest.startsWith('///')) {
      final text = rest.substring(3).trim();
      if (text.isEmpty) {
        if (docBuffer.isNotEmpty) summaryEnded = true;
      } else if (!summaryEnded) {
        docBuffer.add(text);
      }
      continue;
    }

    // One or more annotations, possibly followed by the declaration on the
    // same line (`@Deprecated('…') final double? x;`).
    while (rest.startsWith('@')) {
      final end = _annotationEndOffset(rest);
      if (end == null) {
        openAnnotation.write(rest);
        rest = '';
        break;
      }
      noteAnnotation(rest.substring(0, end));
      rest = rest.substring(end).trim();
    }
    if (rest.isEmpty) continue;

    final match = fieldLine.firstMatch(rest);
    if (match != null) {
      fields.add(
        StyleField(
          type: match.group(1)!.trim(),
          name: match.group(2)!,
          description: docBuffer.isEmpty
              ? null
              : _sanitizeDescription(docBuffer.join(' ')),
          deprecation: pendingDeprecation,
        ),
      );
      docBuffer.clear();
      summaryEnded = false;
      pendingDeprecation = null;
      continue;
    }

    // Any other non-blank, non-doc-comment, non-annotation line breaks
    // doc/field adjacency (section divider comments, getters, the
    // constructor, `static const` defaults, …) — reset so a stray doc block
    // or annotation never attaches to the next unrelated field.
    docBuffer.clear();
    summaryEnded = false;
    pendingDeprecation = null;
  }
  return fields;
}

/// For [text] starting at an annotation's `@`, the offset just past the
/// annotation, or `null` while its argument list is still open.
///
/// Parens inside string literals are not counted — a deprecation message is
/// free prose, and counting an unbalanced `(` in it would either swallow the
/// field after the annotation or end the annotation early.
int? _annotationEndOffset(String text) {
  final name = RegExp(r'^@[\w.]+').firstMatch(text);
  if (name == null) return text.length;
  if (name.end >= text.length || text[name.end] != '(') return name.end;

  var depth = 0;
  String? quote;
  for (var i = name.end; i < text.length; i++) {
    final char = text[i];
    if (quote != null) {
      if (char == r'\') {
        i++;
      } else if (char == quote) {
        quote = null;
      }
      continue;
    }
    if (char == "'" || char == '"') {
      quote = char;
    } else if (char == '(') {
      depth++;
    } else if (char == ')') {
      depth--;
      if (depth == 0) return i + 1;
    }
  }
  return null;
}

final _stringLiteralPattern = RegExp(
  r"'((?:\\.|[^'\\])*)'"
  r'|"((?:\\.|[^"\\])*)"',
);

/// Every string literal in [annotation], joined — Dart's adjacent-literal
/// concatenation, which is how `dart format` wraps a long `@Deprecated`
/// message across lines.
String _stringLiteralText(String annotation) {
  final buffer = StringBuffer();
  for (final match in _stringLiteralPattern.allMatches(annotation)) {
    buffer.write(
      (match.group(1) ?? match.group(2)!).replaceAllMapped(
        RegExp(r'\\(.)'),
        (escape) => escape.group(1)!,
      ),
    );
  }
  return buffer.toString().trim();
}

// `process/deprecation.md` has every deprecation message carry the release
// it started in as `(since <major>.<minor>)`.
final _sincePattern = RegExp(r'\bsince\s+(\d+\.\d+(?:\.\d+)?)');
final _sinceParentheticalPattern = RegExp(
  r'\s*\(\s*since\s+\d+\.\d+(?:\.\d+)?\s*\)',
);

// A doc comment that opens with its own deprecation sentence — written by
// hand while the table could not carry the annotation. The badge now says
// it, so leaving the sentence in would say it twice.
final _leadingDeprecationSentence = RegExp(
  r'^\**deprecated\b(?:.*?[.!?](?=\s|$)|.*$)\s*',
  caseSensitive: false,
);

/// The description cell for [field]: its doc comment, led by a
/// `**Deprecated (since X)** — <message>` notice when the field carries
/// `@Deprecated`.
String describeField(StyleField field) {
  final deprecation = field.deprecation;
  final doc = field.description ?? '';
  if (deprecation == null) return doc;

  final since = _sincePattern.firstMatch(deprecation)?.group(1);
  final badge = since == null
      ? '**Deprecated**'
      : '**Deprecated (since $since)**';
  var message = _sanitizeDescription(
    deprecation.replaceAll(_sinceParentheticalPattern, ''),
  );
  final remainder = doc.replaceFirst(_leadingDeprecationSentence, '').trim();

  if (message.isEmpty) {
    return remainder.isEmpty ? badge : '$badge — $remainder';
  }
  if (remainder.isEmpty) return '$badge — $message';
  if (!RegExp(r'[.!?]$').hasMatch(message)) message = '$message.';
  return '$badge — $message $remainder';
}

/// Strips tracker metadata (`Epic #123`, `Phase 6f`) from an extracted doc
/// comment before it reaches a public doc page.
///
/// `docs_api_sync_test.dart`'s "문서에 tracker 메타가 남아 있지 않다" gate
/// bans exactly this pattern in `docs_core/content/**` — issue numbers are
/// meaningless (and often closed/renumbered) to an external reader. Source
/// doc comments are allowed to reference an Epic for engineers reading the
/// code; this generator's *output* is not, so it scrubs on the way out
/// rather than asking every contract file to avoid the pattern.
// Same pattern `docs_api_sync_test.dart`'s "문서에 tracker 메타가 남아 있지
// 않다" gate matches — kept identical so this scrubber and that gate never
// disagree about what counts as tracker metadata.
final _trackerMetaPattern = RegExp(
  r"(?:Epic|Story|Issue|PR|RFC)\s*#\s*\d+(?:'s)?|Phase\s+\d+[a-z]?",
);

String _sanitizeDescription(String text) {
  return text
      .replaceAll(_trackerMetaPattern, '')
      .replaceAll(RegExp(r'\(\s*\)'), '') // Emptied parenthetical.
      .replaceAll(RegExp(r'\s+'), ' ')
      // Space before punctuation. `String.replaceAll` never interpolates
      // `$1` group references — that's `replaceAllMapped`-only in Dart —
      // so a plain `replaceAll(..., r'$1')` here inserted the four literal
      // characters `$1` in place of the matched punctuation instead of
      // keeping it. Confirmed by shipped output before this fix: e.g.
      // `Button(variant:$1plain, ...)` where `variant: plain)` was intended.
      .replaceAllMapped(
        RegExp(r'\s+([.,)])'),
        (match) => match.group(1)!,
      )
      .trim();
}

// ── Value formatting for defaultsByVariant entries ──────────────────────

final _tokenCallPattern = RegExp(
  r'^CoreColor\.token\(\s*CoreColors\.(\w+)'
  r'(?:,\s*opacity:\s*([^,)]+))?'
  r'(?:,\s*fallbacks:\s*\[([^\]]*)\])?'
  r'.*?\)$',
  dotAll: true,
);
final _dotShorthandPattern = RegExp(r'^\.(\w+)$');
final _tokenAccessPattern = RegExp(r'^Core\w+\.(\w+)$');
final _plainNumberPattern = RegExp(r'^-?\d+(\.\d+)?$');
final _bareIdentifierPattern = RegExp(r'^([a-z]\w*)$');
final _staticConstPattern = RegExp(
  r'static\s+(?:const|final)\s+[\w<>,\s?]+?\s+(\w+)\s*=\s*(.*?);',
  dotAll: true,
);

/// `name` → RHS for every `static const|final` on the parsed class, so a
/// `defaultsByVariant` entry that names one instead of repeating its value
/// can still be rendered as the value.
Map<String, String> sameClassConstants(String classSource) => {
  for (final match in _staticConstPattern.allMatches(classSource))
    match.group(1)!: match.group(2)!,
};

/// Best-effort human-readable rendering of a single field value expression
/// from a `CoreXxxVariantStyle(...)` literal. Recognized shapes collapse to
/// their token name; anything else falls back to the compacted raw
/// expression — never a guess, always either the token name or the real
/// source text.
String formatStyleValue(
  String rawExpression, {
  Map<String, String> siblingConstants = const {},
}) {
  // A row inside a non-`const` map states its values with an explicit
  // `const`, which is not part of the value.
  final expr = rawExpression.trim().replaceFirst(RegExp(r'^const\s+'), '');

  // A table entry may name a sibling `static const` on the same class
  // rather than repeating its value — which is what `core/layer-mapping.md`
  // asks for (one named source, not the same literal twice). Resolve one
  // hop so the doc table still shows the token instead of the constant's
  // name; without this, wiring a default the rule's way makes the table
  // less useful, which is a reason not to do it.
  //
  // One hop only, and only for a bare identifier — a chain would need cycle
  // detection to be safe, and no authored default is more than one deep.
  final bare = _bareIdentifierPattern.firstMatch(expr);
  if (bare != null) {
    final target = siblingConstants[bare.group(1)!];
    if (target != null) return formatStyleValue(target);
  }

  final tokenCall = _tokenCallPattern.firstMatch(expr);
  if (tokenCall != null) {
    final token = tokenCall.group(1)!;
    final opacity = tokenCall.group(2);
    final fallbacks = tokenCall.group(3);
    final parts = <String>[];
    if (opacity != null) {
      final pct = _opacityPercent(opacity.trim());
      parts.add(pct != null ? 'opacity $pct%' : 'opacity ${opacity.trim()}');
    }
    if (fallbacks != null && fallbacks.trim().isNotEmpty) {
      final names = _splitTopLevel(fallbacks).map(_lastSegment).join(', ');
      parts.add('fallback: $names');
    }
    return parts.isEmpty ? token : '$token (${parts.join(', ')})';
  }

  final dotShorthand = _dotShorthandPattern.firstMatch(expr);
  if (dotShorthand != null) return dotShorthand.group(1)!;

  final tokenAccess = _tokenAccessPattern.firstMatch(expr);
  if (tokenAccess != null) return tokenAccess.group(1)!;

  if (_plainNumberPattern.hasMatch(expr)) return expr;

  // Fallback — collapse whitespace from a (possibly multi-line) expression
  // and cap length so the table stays readable. This is always the real
  // source text, never a fabricated summary.
  // A multi-line literal and its single-line twin describe the same value,
  // so they render the same — otherwise two cells of one row disagree on
  // spacing for a reason that is about the source, not the value.
  final collapsed = expr
      .replaceAll(RegExp(r'\s+'), ' ')
      .replaceAll(RegExp(r'\(\s+'), '(')
      .replaceAll(RegExp(r',?\s+\)'), ')')
      .trim();
  return collapsed.length > 64 ? '${collapsed.substring(0, 61)}…' : collapsed;
}

String _lastSegment(String expr) {
  final access = _tokenAccessPattern.firstMatch(expr.trim());
  return access != null ? access.group(1)! : expr.trim();
}

/// `CoreOpacity.opacity80` → `80`. Returns `null` if the token name does
/// not encode a percentage the way that namespace's members do.
int? _opacityPercent(String expr) {
  final match = RegExp(r'^CoreOpacity\.opacity(\d+)$').firstMatch(expr);
  return match == null ? null : int.parse(match.group(1)!);
}

// ── Top-level file parse ─────────────────────────────────────────────────

/// Parses a `{slug}_style.dart` source string. Returns `null` if it does
/// not contain a recognizable `class CoreXxxStyle` — the caller treats
/// that as "skip, do not guess" (see `main()`'s unparsed-coverage report).
ParsedStyleFile? parseStyleFile(String source) {
  final classNameMatch = RegExp(r'class (Core\w+Style)\b').firstMatch(source);
  if (classNameMatch == null) return null;
  final className = classNameMatch.group(1)!;

  final stripped = _stripComments(source);
  final classBody = _bracedBodyAfter(stripped, RegExp('class $className\\b'));
  if (classBody == null) return null;

  // Field doc comments live in the *original* source, at the same offsets
  // `_bracedBodyAfter` found on the stripped copy would not preserve, so
  // re-slice the original using the stripped copy's class-body bounds is
  // unsafe (comment stripping changes line content but not line *count* —
  // `_stripComments` replaces comment text in place, it does not delete
  // lines). Re-run the brace search on the *original* source instead, so
  // offsets are consistent with `source`.
  final classBodyOriginal = _bracedBodyAfter(
    source,
    RegExp('class $className\\b'),
  );
  if (classBodyOriginal == null) return null;
  final fields = _parseFields(classBodyOriginal.body);
  final constants = sameClassConstants(stripped);

  // defaultsByVariant / defaultsByColor (optional).
  final mapDecl = RegExp(
    r'static (?:const|final) Map<(\w+),\s*(\w+)>\s+defaultsBy(Variant|Color)\s*=',
  ).firstMatch(stripped);
  final mapAxis = mapDecl?.group(3);
  final variantDefaults = mapAxis == null
      ? null
      : _parseKeyedRows(stripped, 'defaultsBy$mapAxis', constants);

  // defaultsByTone (optional) — read only when its rows are a row class of
  // their own. A component that keys a partial patch of its own
  // `CoreXxxStyle` by tone (one field per row, merged over other tables)
  // is not the shape this table renders, and reading it would change pages
  // that never asked for a tone table.
  final toneDecl = RegExp(
    r'static const Map<(\w+),\s*(\w+)>\s+defaultsByTone\s*=',
  ).firstMatch(stripped);
  final toneStyleClassName = toneDecl?.group(2);
  final toneDefaults =
      toneStyleClassName == null || toneStyleClassName == className
      ? null
      : _parseKeyedRows(stripped, 'defaultsByTone', constants);

  return ParsedStyleFile(
    className: className,
    fields: fields,
    variantEnumType: variantDefaults == null ? null : mapDecl!.group(1),
    variantStyleClassName: variantDefaults == null ? null : mapDecl!.group(2),
    variantDefaults: variantDefaults ?? const [],
    axisLabel: variantDefaults != null && mapAxis == 'Color' ? '색별' : '변형별',
    toneStyleClassName: toneDefaults == null ? null : toneStyleClassName,
    toneDefaults: toneDefaults ?? const [],
  );
}

/// The rows of the `static const Map<…> $mapName = { … }` (or `static final`,
/// for a row that overlays a token-backed text style) in [stripped],
/// each `Enum.name: RowClass(field: value, …)` as `name` → field → formatted
/// value, in source order. `null` when the map body cannot be found.
List<MapEntry<String, Map<String, String>>>? _parseKeyedRows(
  String stripped,
  String mapName,
  Map<String, String> constants,
) {
  final mapBody = _bracedBodyAfter(stripped, RegExp('$mapName\\s*='));
  if (mapBody == null) return null;

  final rows = <MapEntry<String, Map<String, String>>>[];
  for (final entry in _splitTopLevel(mapBody.body)) {
    // `CoreXxxVariant.name: CoreXxxVariantStyle(args...)`
    final entryMatch = RegExp(
      r'^\w+\.(\w+)\s*:\s*(?:const\s+)?\w+\((.*)\)$',
      dotAll: true,
    ).firstMatch(entry.trim());
    if (entryMatch == null) continue;
    final key = entryMatch.group(1)!;
    final args = _splitTopLevel(entryMatch.group(2)!);
    final values = <String, String>{};
    for (final arg in args) {
      final kv = RegExp(r'^(\w+)\s*:\s*(.*)$', dotAll: true).firstMatch(arg);
      if (kv == null) continue;
      values[kv.group(1)!] = formatStyleValue(
        kv.group(2)!,
        siblingConstants: constants,
      );
    }
    rows.add(MapEntry(key, values));
  }
  return rows;
}

// ── Markdown rendering ───────────────────────────────────────────────────

String _escapeCell(String text) =>
    text.replaceAll('|', r'\|').replaceAll('\n', ' ');

String buildFieldTable(ParsedStyleFile parsed) {
  final buffer = StringBuffer()
    ..writeln('### `${parsed.className}` 필드')
    ..writeln()
    ..writeln('| 필드 | 타입 | 설명 |')
    ..writeln('|------|------|------|');
  for (final field in parsed.fields) {
    final desc = _escapeCell(describeField(field));
    buffer.writeln('| `${field.name}` | `${field.type}` | $desc |');
  }
  return buffer.toString().trimRight();
}

/// `null` when the source has no `defaultsByVariant` / `defaultsByColor` map.
String? buildVariantTable(ParsedStyleFile parsed) => _buildAxisTable(
  className: parsed.className,
  axisLabel: parsed.axisLabel,
  rowClassName: parsed.variantStyleClassName,
  rows: parsed.variantDefaults,
);

/// `null` when the source has no `defaultsByTone` map of its own row class.
String? buildToneTable(ParsedStyleFile parsed) => _buildAxisTable(
  className: parsed.className,
  axisLabel: '톤별',
  rowClassName: parsed.toneStyleClassName,
  rows: parsed.toneDefaults,
);

/// One column per key, one row per field. `null` when there are no rows.
String? _buildAxisTable({
  required String className,
  required String axisLabel,
  required String? rowClassName,
  required List<MapEntry<String, Map<String, String>>> rows,
}) {
  if (rows.isEmpty) return null;

  final keys = rows.map((e) => e.key).toList();
  // Union of field names across all keys, in first-appearance order — a
  // key that omits a field (rare; row-class fields are usually `required`)
  // renders that cell as `—` rather than being dropped.
  final fieldNames = <String>[];
  for (final entry in rows) {
    for (final name in entry.value.keys) {
      if (!fieldNames.contains(name)) fieldNames.add(name);
    }
  }
  if (fieldNames.isEmpty) return null;

  final buffer = StringBuffer()
    ..writeln('### `$className` $axisLabel 기본값 (`$rowClassName`)')
    ..writeln()
    ..write('| 필드 |')
    ..writeln(keys.map((v) => ' `$v` |').join())
    ..write('|------|')
    ..writeln(keys.map((_) => '------|').join());
  for (final field in fieldNames) {
    buffer.write('| `$field` |');
    for (final entry in rows) {
      final value = entry.value[field];
      buffer.write(' ${value == null ? '—' : _escapeCell(value)} |');
    }
    buffer.writeln();
  }
  return buffer.toString().trimRight();
}

String buildGeneratedBlock(ParsedStyleFile parsed) {
  final variantTable = buildVariantTable(parsed);
  final toneTable = buildToneTable(parsed);
  final sections = [
    buildFieldTable(parsed),
    ?variantTable,
    ?toneTable,
  ];
  return sections.join('\n\n');
}

// ── File injection ───────────────────────────────────────────────────────

/// Replaces the content between the marker pair with [generatedBlock].
/// Returns `null` if the markers are not present in [markdown] (the file
/// has not opted in yet — see the class doc comment on the markers).
String? replaceMarkedSection(String markdown, String generatedBlock) {
  final begin = markdown.indexOf(kStyleTableBeginMarker);
  final end = markdown.indexOf(kStyleTableEndMarker);
  if (begin < 0 || end < 0 || end < begin) return null;

  final before = markdown.substring(0, begin + kStyleTableBeginMarker.length);
  final after = markdown.substring(end);
  return '$before\n\n$generatedBlock\n\n$after';
}

// ── CLI ───────────────────────────────────────────────────────────────────

String _underscored(String slug) => slug.replaceAll('-', '_');

File? _styleFileFor(String slug) {
  final dir = Directory(
    'packages/coui_core/lib/src/component/contracts/${_underscored(slug)}',
  );
  if (!dir.existsSync()) return null;
  final file = File('${dir.path}/${_underscored(slug)}_style.dart');
  return file.existsSync() ? file : null;
}

File? _docFileFor(String slug) {
  // 블록으로 옮긴 페이지(`content/blocks`)가 컴포넌트 경로보다 먼저다.
  // Footer 가 그렇다. 둘 다 없으면 null.
  for (final root in const [
    'docs_core/content/blocks',
    'docs_core/content/components',
  ]) {
    final file = File('$root/$slug.md');
    if (file.existsSync()) return file;
  }
  return null;
}

List<String> _allSlugsWithStyleFile() {
  final root = Directory('packages/coui_core/lib/src/component/contracts');
  if (!root.existsSync()) return const [];
  final slugs = <String>[];
  for (final entry in root.listSync().whereType<Directory>()) {
    final name = entry.uri.pathSegments.where((s) => s.isNotEmpty).last;
    if (File('${entry.path}/${name}_style.dart').existsSync()) {
      slugs.add(name.replaceAll('_', '-'));
    }
  }
  slugs.sort();
  return slugs;
}

void main(List<String> args) {
  final write = args.contains('--write');
  final check = args.contains('--check');
  final positional = args.where((a) => !a.startsWith('--')).toList();
  final slugs = positional.isNotEmpty ? positional : _allSlugsWithStyleFile();

  var written = 0;
  var driftFound = 0;
  var skippedNoStyleFile = 0;
  var skippedUnparsed = 0;
  var skippedNoDoc = 0;
  var skippedNoMarkers = 0;

  for (final slug in slugs) {
    final styleFile = _styleFileFor(slug);
    if (styleFile == null) {
      skippedNoStyleFile++;
      continue;
    }
    final parsed = parseStyleFile(styleFile.readAsStringSync());
    if (parsed == null || parsed.fields.isEmpty) {
      skippedUnparsed++;
      print('⚠ skip $slug — could not parse ${styleFile.path}');
      continue;
    }

    final docFile = _docFileFor(slug);
    if (docFile == null) {
      skippedNoDoc++;
      continue;
    }
    final markdown = docFile.readAsStringSync();
    final generated = buildGeneratedBlock(parsed);
    final replaced = replaceMarkedSection(markdown, generated);
    if (replaced == null) {
      skippedNoMarkers++;
      continue;
    }

    if (replaced == markdown) continue; // Already up to date.

    if (write) {
      docFile.writeAsStringSync(replaced);
      written++;
      print('✓ wrote $slug');
    } else if (check) {
      driftFound++;
      print(
        '✗ drift: ${docFile.path} is stale relative '
        'to ${styleFile.path}',
      );
    }
  }

  print(
    '\n${slugs.length} slugs considered · $written written · '
    '$driftFound drifted · '
    '$skippedNoMarkers not opted in (no markers) · $skippedUnparsed unparsed · '
    '$skippedNoDoc no doc file · $skippedNoStyleFile no style file',
  );

  if (check && driftFound > 0) exit(1);
}
