// Generates `lib/src/components/display/code_snippet/code_snippet_grammars.g.dart`
// — the TextMate grammars `CodeSnippet` registers besides Dart, as Dart
// constants.
//
// Flutter loads these grammars as package assets
// (`packages/coui_flutter/assets/syntax_grammars/`). A Jaspr page has no asset
// bundle to load from, so the Web package carries the same bytes compiled in.
// The asset files are the source: this tool copies them, and a test fails
// when the copy and the files differ — so the two platforms cannot paint a
// language from different grammars.
//
// Run from the repo root:
//
//   dart run packages/coui_web/tool/gen_code_snippet_grammars.dart          # write
//   dart run packages/coui_web/tool/gen_code_snippet_grammars.dart --check  # verify
import 'dart:convert';
import 'dart:io';

const _kSourceDir = 'packages/coui_flutter/assets/syntax_grammars';
const _kOutputPath =
    'packages/coui_web/lib/src/components/display/code_snippet/'
    'code_snippet_grammars.g.dart';

/// The grammars the highlighter does not embed, by the name the contract's
/// table gives them (`CoreCodeSnippetContract.grammarOf`).
const kGeneratedLanguages = ['json', 'sql', 'yaml'];

Future<void> main(List<String> args) async {
  if (args.contains('--check')) {
    if (!await isUpToDate()) {
      stderr.writeln(
        '$_kOutputPath is out of date — a grammar under $_kSourceDir '
        'changed.\n'
        'Run: dart run packages/coui_web/tool/gen_code_snippet_grammars.dart',
      );
      exitCode = 1;

      return;
    }
    stdout.writeln('$_kOutputPath is up to date.');

    return;
  }
  File(_path(_kOutputPath)).writeAsStringSync(await _formatted(generate()));
  stdout.writeln('Wrote $_kOutputPath.');
}

/// Whether the committed file is exactly what this tool would write now.
Future<bool> isUpToDate() async {
  final output = File(_path(_kOutputPath));
  final generated = await _formatted(generate());

  return output.existsSync() && output.readAsStringSync() == generated;
}

/// The asset file a grammar is copied from.
String sourceOf(String language) =>
    File(_path('$_kSourceDir/$language.json')).readAsStringSync();

/// The repo root — the nearest ancestor of the working directory that holds
/// the grammar assets — so the tool runs from the root and the package's
/// tests run from `packages/coui_web`.
final String _repoRoot = () {
  var dir = Directory.current.absolute;
  while (!Directory('${dir.path}/$_kSourceDir').existsSync()) {
    final parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError('$_kSourceDir not found above the working dir');
    }
    dir = parent;
  }

  return dir.path;
}();

String _path(String repoRelative) => '$_repoRoot/$repoRelative';

/// [source] as `dart format` leaves it at [_kOutputPath].
///
/// The source goes in on stdin and comes back on stdout, so nothing is
/// written to disk: a scratch file beside the output would sit under `lib/`,
/// where tests that walk the package's sources would list it.
Future<String> _formatted(String source) async {
  // Under `dart` the running VM is the formatter; under any other host
  // (a test runner binary) fall back to the `dart` on PATH.
  final vm = Platform.resolvedExecutable;
  final dart = RegExp(r'dart(\.exe)?$').hasMatch(vm) ? vm : 'dart';
  final process = await Process.start(dart, [
    // Stdout is the result here, so no first-run notice may land on it.
    '--suppress-analytics',
    'format',
    '--stdin-name=${_path(_kOutputPath)}',
  ]);
  final formatted = process.stdout.transform(utf8.decoder).join();
  final diagnostics = process.stderr.transform(utf8.decoder).join();
  process.stdin.add(utf8.encode(source));
  await process.stdin.close();
  final status = await process.exitCode;
  final output = await formatted;
  final warnings = await diagnostics;
  if (status != 0 || warnings.isNotEmpty) {
    throw StateError('dart format failed for $_kOutputPath:\n$warnings');
  }

  return output;
}

/// The generated source for the current asset files.
String generate() {
  final buffer = StringBuffer()
    ..writeln(
      '// GENERATED by packages/coui_web/tool/gen_code_snippet_grammars.dart',
    )
    ..writeln('// from $_kSourceDir — do not edit by hand.')
    ..writeln('//')
    ..writeln(
      "// The grammars are third-party work: provenance in that directory's",
    )
    ..writeln("// README, licence terms in this package's LICENSE.")
    ..writeln()
    ..writeln(
      '/// The TextMate grammar `CodeSnippet` registers for [language], or',
    )
    ..writeln(
      '/// `null` when there is none to register — Dart, which the highlighter',
    )
    ..writeln("/// embeds, and any name the contract's table does not give.")
    ..writeln('///')
    ..writeln(
      '/// The same bytes Flutter loads as package assets; a test compares the',
    )
    ..writeln('/// two.')
    ..writeln('String? codeSnippetGrammarSource(String language) =>')
    ..writeln('    switch (language) {');
  for (final language in kGeneratedLanguages) {
    buffer.writeln("      '$language' => ${_constantName(language)},");
  }
  buffer
    ..writeln('      _ => null,')
    ..writeln('    };');

  for (final language in kGeneratedLanguages) {
    final source = sourceOf(language);
    // A raw string ends at the first `'''`; none of the grammars holds one.
    if (source.contains("'''")) {
      throw StateError("$language.json holds ''' — it cannot be a raw string");
    }
    buffer
      ..writeln()
      ..writeln("const String ${_constantName(language)} = r'''")
      // The newline after the opening quotes is not part of the string, so
      // the constant is the file byte for byte.
      ..write(source)
      ..writeln("''';");
  }

  return buffer.toString();
}

String _constantName(String language) =>
    '_k${language[0].toUpperCase()}${language.substring(1)}Grammar';
