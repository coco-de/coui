/// Horizontal position of an indicator item relative to the wrapped child.
enum CoreIndicatorHorizontalPosition {
  /// Start edge (left in LTR).
  start,

  /// Horizontal center.
  center,

  /// End edge (right in LTR, default).
  end,
}

/// Vertical position of an indicator item relative to the wrapped child.
enum CoreIndicatorVerticalPosition {
  /// Top edge (default).
  top,

  /// Vertical middle.
  middle,

  /// Bottom edge.
  bottom,
}
