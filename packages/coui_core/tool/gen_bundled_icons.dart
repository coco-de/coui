// Generates `lib/src/icon/bundled_icons.g.dart` — the SVG data of every
// icon CoUI's own components draw, so they render without a network
// request (#5149).
//
// The set is whatever `LucideIcons.<member>` the two platform packages
// reference under `lib/`; the data comes from the vendored, version-pinned
// Lucide collection the parity harness already ships (see
// `tool/parity/vendor/iconify/README.md` for provenance and sha256).
//
// Run from the repo root:
//
//   dart run packages/coui_core/tool/gen_bundled_icons.dart          # write
//   dart run packages/coui_core/tool/gen_bundled_icons.dart --check  # verify
import 'dart:convert';
import 'dart:io';

const _kCollectionPath = 'tool/parity/vendor/iconify/lucide-1.2.121.json';
const _kLucideIconsPath = 'packages/coui_core/lib/src/icon/lucide_icons.dart';
const _kOutputPath = 'packages/coui_core/lib/src/icon/bundled_icons.g.dart';
const _kScannedRoots = ['packages/coui_flutter/lib', 'packages/coui_web/lib'];

Future<void> main(List<String> args) async {
  if (args.contains('--check')) {
    if (!await isUpToDate()) {
      stderr.writeln(
        '$_kOutputPath is out of date — a component started drawing an '
        'icon the bundle does not carry, or stopped drawing one.\n'
        'Run: dart run packages/coui_core/tool/gen_bundled_icons.dart',
      );
      exitCode = 1;

      return;
    }
    stdout.writeln('$_kOutputPath is up to date.');

    return;
  }
  File(_path(_kOutputPath)).writeAsStringSync(await _formatted(generate()));
  stdout.writeln('Wrote $_kOutputPath.');
}

/// Whether the committed bundle is exactly what this tool would write now.
Future<bool> isUpToDate() async {
  final output = File(_path(_kOutputPath));
  final generated = await _formatted(generate());

  return output.existsSync() && output.readAsStringSync() == generated;
}

/// The repo root — the nearest ancestor of the working directory that
/// holds the vendored collection — so the tool runs from the root and the
/// package's tests run from `packages/coui_core`.
final String _repoRoot = () {
  var dir = Directory.current.absolute;
  while (!File('${dir.path}/$_kCollectionPath').existsSync()) {
    final parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError('$_kCollectionPath not found above the working dir');
    }
    dir = parent;
  }

  return dir.path;
}();

String _path(String repoRelative) => '$_repoRoot/$repoRelative';

/// [source] as `dart format` leaves it at [_kOutputPath].
///
/// The source goes in on stdin and comes back on stdout; `--stdin-name`
/// makes the formatter resolve that path's `analysis_options.yaml` and
/// language version exactly as it would for the file itself. Nothing is
/// written to disk: a scratch file beside the output would sit under
/// `lib/`, where every test that walks the package's sources lists it, and
/// `dart test` runs test files in parallel — a walker that listed it before
/// it was deleted fails reading it.
Future<String> _formatted(String source) async {
  // Under `dart` the running VM is the formatter; under any other host
  // (a test runner binary) fall back to the `dart` on PATH.
  final vm = Platform.resolvedExecutable;
  final dart = RegExp(r'dart(\.exe)?$').hasMatch(vm) ? vm : 'dart';
  final process = await Process.start(dart, [
    // Stdout is the result here, so no first-run notice may land on it.
    '--suppress-analytics',
    'format',
    '--stdin-name=${_path(_kOutputPath)}',
  ]);
  final formatted = process.stdout.transform(utf8.decoder).join();
  final diagnostics = process.stderr.transform(utf8.decoder).join();
  process.stdin.add(utf8.encode(source));
  await process.stdin.close();
  final status = await process.exitCode;
  final output = await formatted;
  // The formatter says nothing on stderr when it formats. A parse error
  // exits non-zero; an `include:` it cannot resolve only warns, exits 0 and
  // formats with the default options — either way the bytes are not what
  // `dart format` makes of the committed file.
  final warnings = await diagnostics;
  if (status != 0 || warnings.isNotEmpty) {
    throw StateError('dart format failed for $_kOutputPath:\n$warnings');
  }

  return output;
}

/// The generated source for the current tree.
String generate() {
  final memberToName = _lucideMembers();
  final referenced = _referencedMembers();
  final unknown = referenced.difference(memberToName.keys.toSet());
  if (unknown.isNotEmpty) {
    throw StateError('Unknown LucideIcons members: ${unknown.join(', ')}');
  }

  final collection =
      jsonDecode(File(_path(_kCollectionPath)).readAsStringSync())
          as Map<String, dynamic>;
  final names = {for (final m in referenced) memberToName[m]!}.toList()..sort();

  final buffer = StringBuffer()
    ..writeln('// GENERATED by packages/coui_core/tool/gen_bundled_icons.dart')
    ..writeln('// from $_kCollectionPath — do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:coui_core/src/icon/icon_data.dart';")
    ..writeln()
    ..writeln(
      '/// SVG data of every icon CoUI components draw, keyed by icon id.',
    )
    ..writeln('///')
    ..writeln(
      '/// Lets a component icon render on its first frame with no network',
    )
    ..writeln('/// request — offline, behind a strict CSP, in a widget test.')
    ..writeln(
      '/// Regenerate with `tool/gen_bundled_icons.dart` when a component',
    )
    ..writeln(
      '/// starts drawing a new icon — a coverage test fails until it does.',
    )
    ..writeln('abstract final class CoreBundledIcons {')
    ..writeln('  const CoreBundledIcons._();')
    ..writeln()
    ..writeln('  /// Icon id (`prefix:name`) → SVG data.')
    ..writeln('  static const Map<String, IconSvgData> icons = {');
  for (final name in names) {
    final icon = _resolve(collection, name);
    final width = icon['width'] as int? ?? collection['width'] as int? ?? 24;
    final height = icon['height'] as int? ?? collection['height'] as int? ?? 24;
    buffer
      ..writeln("    'lucide:$name': IconSvgData(")
      ..writeln('      body: ${_dartString(icon['body']! as String)},')
      ..writeln('      width: $width,')
      ..writeln('      height: $height,')
      ..writeln('    ),');
  }
  buffer
    ..writeln('  };')
    ..writeln('}');

  return buffer.toString();
}

Map<String, Object?> _resolve(Map<String, dynamic> collection, String name) {
  final icons = collection['icons'] as Map<String, dynamic>;
  final aliases = (collection['aliases'] as Map<String, dynamic>?) ?? {};
  if (icons[name] case final Map<String, dynamic> icon) return icon;
  if (aliases[name] case {'parent': final String parent}) {
    return _resolve(collection, parent);
  }
  throw StateError('lucide:$name is not in $_kCollectionPath');
}

/// `LucideIcons.<member>` → icon name, read from the constants file (a
/// member's declaration may wrap across lines).
Map<String, String> _lucideMembers() {
  final source = File(_path(_kLucideIconsPath)).readAsStringSync();
  final declaration = RegExp(
    r"static const (\w+)\s*=\s*IconName\(\s*_p,\s*'([^']+)'",
  );

  return {
    for (final match in declaration.allMatches(source))
      match.group(1)!: match.group(2)!,
  };
}

Set<String> _referencedMembers() {
  final reference = RegExp(r'\bLucideIcons\.(\w+)');
  final members = <String>{};
  for (final root in _kScannedRoots) {
    for (final entity in Directory(_path(root)).listSync(recursive: true)) {
      if (entity is! File || !entity.path.endsWith('.dart')) continue;
      for (final match in reference.allMatches(entity.readAsStringSync())) {
        members.add(match.group(1)!);
      }
    }
  }

  return members;
}

/// A single-quoted Dart literal; Lucide bodies carry double quotes only.
String _dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');

  return "'$escaped'";
}
